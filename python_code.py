import pandas as pd
import numpy as np 
df = pd.read_excel("farmers_raw.xlsx")
print(df.head())
print(df.shape)
print(df.shape)
print(df.isna().sum())
print(df["City"].value_counts())
print(df.duplicated().sum())
df = df.drop_duplicates()
df = df.reset_index(drop=True)
print(df.shape)
print(sorted(df["City"].unique()))
df["City"] = df["City"].str.strip()
df["City"] = df["City"].str.title()
df["City"] = df["City"].replace({"Nasik": "Nashik"})
print(sorted(df["City"].unique()))
print(df[df["Age"] > 80])
print(df[(df["Age"] > 80) | (df["Age"] < 18)])
df.loc[(df["Age"] > 80) | (df["Age"] < 18), "Age"] = np.nan
print(df["Age"].isna().sum())
print(df[df["Age"].isna()][["Farmer_ID", "Age"]])
q1 = df["Monthly_Income"].quantile(0.25)
q3 = df["Monthly_Income"].quantile(0.75)
print(q1, q3)
df["Age"] = df["Age"].fillna(df["Age"].median())
print(df["Age"].isna().sum())
print(df.loc[[4, 17, 21, 33], ["Farmer_ID", "Age"]])
df["Land_Acres"] = df["Land_Acres"].fillna(df["Land_Acres"].median())
print(df["Land_Acres"].isna().sum())
print(df["Crop"].mode()[0])
df["Crop"] = df["Crop"].fillna(df["Crop"].mode()[0])
print(df["Crop"].isna().sum())
print(df[df["Monthly_Income"] > 100000][["Farmer_ID", "Monthly_Income"]])
df.loc[df["Monthly_Income"] > 100000, "Monthly_Income"] = np.nan
print(df["Monthly_Income"].isna().sum())
print(df["Monthly_Income"].median())
df["Monthly_Income"] = df["Monthly_Income"].fillna(df["Monthly_Income"].median())
print(df["Monthly_Income"].isna().sum())
print(df.isna().sum())
df["Yearly_Income"] = df["Monthly_Income"] * 12
print(df[df["Farmer_ID"] == "F031"][["Farmer_ID", "Monthly_Income", "Yearly_Income"]])
df["Profit"] = df["Yearly_Income"] - df["Yearly_Expense"]
print(df["Profit"].isna().sum())
print(df.dtypes)
df["Age"] = df["Age"].astype(int)
print(df["Age"].dtype)
df["Profit_Margin"] = (df["Profit"] / df["Yearly_Income"] * 100).round(1)
print(df[["Farmer_ID", "Profit", "Yearly_Income", "Profit_Margin"]].head())
df["Farmer_Type"] = np.where(df["Land_Acres"] < 10, "Small", "Large")
print(df["Farmer_Type"].value_counts())
df["Age_Group"] = pd.cut(df["Age"], bins=[17, 30, 45, 60, 100], labels=["18-30", "31-45", "46-60", "60+"])
print(df["Age_Group"].value_counts())
df["Age_Group"] = pd.cut(df["Age"], bins=[17, 30, 45, 60, 100], labels=["18-30", "31-45", "46-60", "60+"])
print(df["Age_Group"].value_counts())
print(df.sort_values("Profit", ascending=False).head(5)[["Farmer_ID", "Farmer_Name", "City", "Profit"]])
df.to_csv("farmers_clean.csv", index=False)
